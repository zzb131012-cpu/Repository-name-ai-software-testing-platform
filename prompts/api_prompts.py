def build_api_test_point_prompt(
    api_name,
    request_method,
    api_url,
    api_description,
    api_analysis,
    skill_context="",
):
    return f"""
你是一名专业的软件测试工程师。

请根据接口需求、接口分析以及测试 Skill，
生成完整、细粒度的接口测试点。

====================
接口名称
====================

{api_name}

====================
请求方式
====================

{request_method}

====================
接口URL
====================

{api_url}

====================
接口需求
====================

{api_description}

====================
接口分析
====================

{api_analysis}

====================
测试 Skill
====================

{skill_context}

====================
最高优先级原则
====================

1. 当前需求是最高事实来源。
2. Skill 是测试设计辅助规则，不是新的业务需求。
3. Skill 与当前需求冲突时，以当前需求为准。
4. 不允许为接口不存在的字段生成确定性测试点。
5. 不允许把响应字段当成请求字段。
6. 需求没有明确的业务预期必须标记：
【需求待确认】
7. 不允许凭空增加：
   - 验证码
   - refresh_token
   - 限流
   - 账号体系
   - 多端登录
   - 额外请求字段
   等确定业务规则。

====================
测试点粒度要求
====================

必须遵循：

一个独立输入条件
=
一个独立测试点。

禁止把多个不同测试条件合并成一个测试点。

例如字段规则：

password 长度 6~20 位

必须分别设计：

- 长度5
- 长度6
- 长度7
- 长度19
- 长度20
- 长度21

不能只写：

“测试 password 长度边界”。

如果字段要求固定11位：

必须分别设计：

- 10位
- 11位
- 12位

如果字段必填：

必须尽量分别设计：

- 字段缺失
- 空字符串
- null

不能合并成：

“字段为空测试”。

错误 HTTP Method：

GET
PUT
PATCH
DELETE

应分别作为独立测试点。

====================
覆盖要求
====================

重点覆盖：

1. 正常场景
2. 必填校验
3. 空字符串
4. null
5. 字段缺失
6. 字段类型
7. 有效等价类
8. 无效等价类
9. 下边界外
10. 下边界
11. 下边界内
12. 上边界内
13. 上边界
14. 上边界外
15. HTTP Method
16. Headers
17. Content-Type
18. 空 Request Body
19. 非法 JSON
20. 错误 JSON 类型
21. HTTP 状态码
22. 业务 code
23. 响应必填字段
24. 响应字段类型
25. 请求超时
26. 服务异常
27. 网络异常
28. 安全风险

====================
去重规则
====================

“去重”只表示：

完全相同的输入条件 + 完全相同的验证目标
只能保留一个。

以下不是重复：

- password 长度5
- password 长度6
- password 长度7

以下也不是重复：

- phone 缺失
- phone=""
- phone=null

这些都必须分别保留。

请输出结构清晰、细粒度的接口测试点。
""".strip()


def build_api_case_prompt(
    api_name,
    request_method,
    api_url,
    api_description,
    headers_text,
    request_body,
    success_response,
    error_response,
    api_test_points,
    skill_context="",
):
    return f"""
你是一名专业的软件测试工程师。

请根据接口信息、接口测试点和测试 Skill，
生成可以直接用于测试执行和自动化的结构化接口测试用例。

====================
接口名称
====================

{api_name}

====================
请求方式
====================

{request_method}

====================
接口URL
====================

{api_url}

====================
接口需求
====================

{api_description}

====================
Headers
====================

{headers_text}

====================
Request Body / Params
====================

{request_body}

====================
成功响应示例
====================

{success_response}

====================
异常响应示例
====================

{error_response}

====================
接口测试点
====================

{api_test_points}

====================
测试 Skill
====================

{skill_context}

====================
第一原则：一个场景一条用例
====================

这是最高优先级要求。

每一个具有不同：

- 输入值
- 边界值
- 字段状态
- HTTP Method
- Header状态
- 请求体状态
- 业务状态

的场景，都必须生成独立测试用例。

禁止把多个独立场景合并到一条用例。

例如：

错误写法：

“验证手机号为空、缺失、null”

正确写法：

APIxxx 手机号字段缺失
APIxxx 手机号为空字符串
APIxxx 手机号为null

错误写法：

“验证password边界值”

正确写法：

APIxxx password长度5位
APIxxx password长度6位
APIxxx password长度7位
APIxxx password长度19位
APIxxx password长度20位
APIxxx password长度21位

错误写法：

“验证错误请求方法”

正确写法：

APIxxx 使用GET请求
APIxxx 使用PUT请求
APIxxx 使用PATCH请求
APIxxx 使用DELETE请求

====================
边界值强制要求
====================

如果 Skill 已给出：

固定长度 N：

必须分别生成：

N-1
N
N+1

例如11位：

10
11
12

如果 Skill 给出：

最小值 min
最大值 max

必须分别生成：

min-1
min
min+1
max-1
max
max+1

例如6~20：

5
6
7
19
20
21

这些不同边界不得合并。

====================
等价类强制要求
====================

如果 Skill 中存在以下等价类，
必须尽量分别生成：

- 字段缺失
- 空字符串
- null
- 正常值
- 错误类型
- 非法字符
- 格式错误

对于：

__MISSING__

含义是：

请求 JSON 中完全不包含该字段。

不是：

"field": "__MISSING__"

====================
业务规则
====================

1. 当前接口需求是最高事实来源。
2. Skill 只能补充测试方法。
3. Skill 不可以新增业务规则。
4. 不允许凭空新增请求字段。
5. 不允许把响应字段作为请求参数。
6. 对需求没有定义的确定预期：
   必须写【需求待确认】。
7. 不允许为了增加用例数量编造业务场景。

====================
用例独立性
====================

除专门组合测试外：

每条参数校验用例只修改一个主要变量。

例如测试：

phone 10位

则 password 应保持合法。

测试：

password 5位

则 phone 应保持合法。

这样才能明确定位测试失败原因。

====================
优先级严格规则
====================

priority 字段只有三个合法值：

"P0"
"P1"
"P2"

禁止输出：

- 高
- 中
- 低
- P3
- P0级
- P1级
- 空字符串
- null

优先级参考：

P0：
核心主流程、重要业务规则、严重异常、安全核心场景。

P1：
主要参数校验、边界、等价类、主要异常。

P2：
低风险兼容性、补充性场景。

每一条用例都必须填写 priority。

====================
HTTP规则
====================

method 必须是标准 HTTP Method：

GET
POST
PUT
PATCH
DELETE
HEAD
OPTIONS

不得输出其他字符串。

expected_http_status 必须使用：

100~599

范围内的标准 HTTP 状态码。

如果需求没有明确状态码，但该测试点仍有必要：

根据需求确定是否可以合理得到状态码。

无法确定时应避免编造确定状态码。

====================
完整性要求
====================

每条用例必须包含：

1. case_id
2. module
3. title
4. method
5. url
6. headers
7. request_data
8. expected_http_status
9. expected_business_result
10. priority

其中：

title 不允许为空。

url 不允许为空。

expected_http_status 不允许为空。

expected_business_result 不允许为空。

priority 不允许为空。

====================
用例标题要求
====================

标题必须能单独看懂测试目的。

推荐：

手机号长度10位校验
手机号为空字符串校验
密码长度5位校验
使用GET访问POST接口
Content-Type缺失校验

不要使用：

异常测试1
边界测试
参数测试
测试接口

====================
去重规则
====================

只有以下情况才算重复：

输入条件相同
+
测试目的相同
+
预期相同

才允许删除。

以下不是重复：

5位 / 6位 / 7位

10位 / 11位 / 12位

缺失 / 空字符串 / null

GET / PUT / PATCH / DELETE

必须分别保留。

====================
输出格式
====================

只返回合法 JSON 数组。

不要返回任何解释文字。

不要返回 Markdown。

不要返回 ```json。

不要在 JSON 前后增加任何字符。

示例：

[
  {{
    "case_id": "API001",
    "module": "用户登录",
    "title": "正确手机号和密码登录成功",
    "method": "POST",
    "url": "{api_url}",
    "headers": "{{\\"Content-Type\\": \\"application/json\\"}}",
    "request_data": "{{\\"phone\\": \\"13800138000\\", \\"password\\": \\"123456\\"}}",
    "expected_http_status": "200",
    "expected_business_result": "登录成功，code=0",
    "priority": "P0"
  }}
]
""".strip()


